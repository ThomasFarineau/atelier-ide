use super::*;

#[test]
fn descriptions_lose_every_attribution() {
    let body = "Adds the pr command.\r\n\n- checks the commits\n\nCo-authored-by: Someone <a@b.c>\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\nGenerated by an AI\n";
    assert_eq!(
        clean_description(body),
        "Adds the pr command.\n\n- checks the commits"
    );
    assert_eq!(
        clean_description("Nothing to remove."),
        "Nothing to remove."
    );
}

#[test]
fn the_command_is_offered_and_names_its_tools() {
    assert_eq!(prompts()[0]["name"], "pr");
    let text = prompt("pr", &serde_json::json!({"base": "dev"})).unwrap();
    assert!(text.contains("git_pr_plan") && text.contains("git_pull_request"));
    assert!(text.contains("“dev”"));
    assert!(prompt("commit", &serde_json::json!({})).is_none());
}

#[test]
fn a_branch_is_read_against_its_base() {
    let dir = std::env::temp_dir().join(format!("atelier-pr-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let git = |args: &[&str]| {
        let out = std::process::Command::new("git")
            .args([
                "-c",
                "user.name=T",
                "-c",
                "user.email=t@t",
                "-c",
                "commit.gpgsign=false",
            ])
            .args(args)
            .current_dir(&dir)
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
    };
    git(&["init", "-q", "-b", "main"]);
    std::fs::write(dir.join("a.txt"), "a\n").unwrap();
    git(&["add", "."]);
    git(&["commit", "-q", "-m", "feat: start"]);
    git(&["switch", "-q", "-c", "work"]);
    std::fs::write(dir.join("a.txt"), "b\n").unwrap();
    git(&["commit", "-q", "-am", "fix: change a"]);
    let found: serde_json::Value =
        serde_json::from_str(&plan(&dir, &serde_json::json!({"base": "main"})).unwrap()).unwrap();
    assert_eq!(found["branch"], "work");
    assert_eq!(found["commits"].as_array().unwrap().len(), 1);
    assert_eq!(found["commitsBreakingTheRules"], 0);
    assert!(found["diff"].as_str().unwrap().contains("+b"));
    // A title that breaks the rules is refused before anything is pushed.
    let refused = create(
        &dir,
        &serde_json::json!({"base": "main", "title": "Change a", "body": "Changes a."}),
    )
    .unwrap_err();
    assert!(refused.starts_with("title:"), "{refused}");
    git(&["switch", "-q", "main"]);
    assert!(
        plan(&dir, &serde_json::json!({"base": "main"})).is_err(),
        "on the base"
    );
    let _ = std::fs::remove_dir_all(&dir);
}
